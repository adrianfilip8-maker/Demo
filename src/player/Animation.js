const OPEN_JOINTS = {
  lowerArmL: 'elbow', lowerArmR: 'elbow',
  lowerLegL: 'knee', lowerLegR: 'knee',
};

/**
 * Distal-joint tracks scaled toward bind — the one transform behind the lever above. Slerping
 * toward identity shrinks the fold along the joint's OWN axis, so a bent elbow straightens
 * without acquiring a direction the animator never gave it; k = 0 returns the clip untouched
 * by object identity, which is what makes the faithful arm bit-exact rather than nearly so.
 */
function openLimbs(clip, k) {
  if (!k.elbow && !k.knee) return clip;
  const I = new THREE.Quaternion();
  const q = new THREE.Quaternion();
  const bones = clip.bones.map((tr) => {
    const joint = OPEN_JOINTS[tr.name];
    const kk = joint ? k[joint] : 0;
    if (!kk) return tr;
    const out = new Float32Array(tr.q.length);
    for (let i = 0; i < tr.q.length; i += 4) {
      q.set(tr.q[i], tr.q[i + 1], tr.q[i + 2], tr.q[i + 3]);
      q.slerp(I, kk);                      // shrink the fold toward bind by k, same axis
      out[i] = q.x; out[i + 1] = q.y; out[i + 2] = q.z; out[i + 3] = q.w;
    }
    return { ...tr, q: out };
  });
  return { ...clip, bones };
}

/**
 * §479.8 — a raw clip cut to [from, until] of its own timeline, keys rebased to t=0. Cuts land
 * on the emitter's 0.05 s key grid, so no key is interpolated, only dropped.
 *
 * Its live use is `until` alone, cutting dead tails: `PickPocket` is exported as a 4 s
 * idle-bake whose motion is over by ~0.6 s, and it ships cut to the 1.1 s the pickpocket state
 * actually spends on it. `from` exists and is tested, but NOTHING ships with a head trim, and
 * that is the deliberate outcome of §479.8's correction rather than an accident: the first pass
 * of the combat port trimmed 0.25–0.30 s off `Canehit`'s head to "skip the windup" and thereby
 * deleted the strike itself (see the alias table — the clip contacts at t 0.10, the fast moment
 * late in it is the recovery). A head trim on an authored clip removes an action, not a pause;
 * it needs a measurement of what is inside the cut before it is used again.
 */
function trimRaw(raw, from = 0, until = raw.dur) {
  if (!from && until >= raw.dur) return raw;
  const keys = raw.keys.filter((k) => k.t >= from - 1e-6 && k.t <= until + 1e-6)
    .map((k) => ({ ...k, t: +(k.t - from).toFixed(4) }));
  return {
    ...raw, dur: +(until - from).toFixed(4), keys,
    events: raw.events ? raw.events.filter((e) => e.t >= from && e.t <= until)
      .map((e) => ({ ...e, t: e.t - from })) : raw.events,
  };
}

/**
 * §479.18 — a raw clip played BACKWARDS, because their tree plays two of these backwards and a
 * name match cannot see it. Godot's `AnimationNodeAnimation.play_mode = 1` is PLAY_MODE_BACKWARD,
 * and exactly two nodes in `sly_cooper_anims_4.tscn` carry it — both of them clips we swapped:
 * `Library_Sly_19/PoleClimbing` (their `pole_state`/"pole_walk") and `Library_Sly_19/CaneSwing`.
 * Only the first one needs this: measured pose-against-pose over the whole cycle, PoleClimbing
 * is DIRECTIONAL (forward-vs-reversed differs by 35.4° worst at the forearm, mean 8.7°) while
 * CaneSwing is PALINDROMIC (worst 0.2° — its reversal is invisible, so `hook_swing` is left
 * alone rather than churned). Safe as a key-list flip because every key godot2clips emits is
 * `lin` — there is no asymmetric ease to mirror.
 */
function reverseRaw(raw) {
  const dur = raw.dur;
  const keys = raw.keys.map((k) => ({ ...k, t: +(dur - k.t).toFixed(4) })).reverse();
  return {
    ...raw, keys,
    events: raw.events ? raw.events.map((e) => ({ ...e, t: +(dur - e.t).toFixed(4) })).reverse() : raw.events,
  };
}

/** A raw authoring-format clip replayed over a different duration (events rescale with it). */
function retimeRaw(raw, dur) {
  if (!dur || dur === raw.dur) return raw;
  const k = dur / raw.dur;
  return {
    ...raw, dur,
    keys: raw.keys.map((key) => ({ ...key, t: +(key.t * k).toFixed(4) })),
    events: raw.events ? raw.events.map((e) => ({ ...e, t: e.t * k })) : raw.events,
  };
}

