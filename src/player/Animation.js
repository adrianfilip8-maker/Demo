/**
 * `MIXAMO_CLIPS` (generated by `tools/mixamo2clips.mjs`) is 16 clips retargeted onto RIG3 from a
 * fan project's authored animation. It is emitted in `Clips.js`'s **authoring** format on purpose,
 * so it comes through `Clips.js`'s own `compile()` — same eases, same `eulerDeg`, same sparse-key
 * rule, sampled by the same `slerp`. `compile()` is exported for exactly this; the alternative was
 * a second compiler here, and §212's cost was a second, subtly different account of the
 * authoring→runtime interchange being reasoned about as if it were the real one. One copy.
 *
 * ── The map is 16 → 14, and it is not a 1:1 substitution ────────────────────────────────
 * §4.7 requires 52 clip names. Mixamo supplies 13 usable sources covering 14 of them, so **38 of
 * 52 have no counterpart and stay procedural whatever the token says**. `walk_side_left/right`
 * have no game slot at all (nothing in the 52 strafes) and `fall_pose_02` is a 0.067 s static pose
 * with nowhere sensible to go; all three are deliberately unused rather than given an invented job.
 *
 * ── What Mixamo cannot supply, and how the mixed regime fills it ────────────────────────
 * Mixamo has no tail, no cane, no ears, no brow, no jaw, no cap. That is 10 of RIG3's 31 bones,
 * and four of them are the tail — "half his silhouette" by `Rig.js`'s own account. So the mixed
 * regime is stated as ONE rule rather than a list of exceptions:
 *
 *     a mixed clip takes Mixamo's track for every bone Mixamo has, and the procedural
 *     counterpart's track — time-scaled onto the new duration — for every bone it does not,
 *     plus that counterpart's cane track.
 *
 * Time-scaling is what makes it a splice rather than a collision: `walk` is 1.0 s and
 * `walk_forward` is 1.7 s, and an unscaled donor track would run out at 1.0 s and freeze the tail
 * for the remaining 0.7 s of every cycle. Both are cycles, so scaling the donor's key times by
 * `durNew/durOld` phase-matches them.
 *
 * `mixamo-pure` exists to isolate that fill: same 14 clips with NO donor tracks, so the tail, cane
 * and face sit at bind and only the spring layers move them. It is the arm that says how much of
 * the mixed regime's look is Mixamo and how much is the procedural set still doing the work.
 */
