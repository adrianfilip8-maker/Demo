/** Bones RIG3 has and Mixamo does not — the fill list, derived rather than typed twice. */
function donorBones(mixClip) {
  const has = new Set(mixClip.bones.map((t) => t.name));
  return (name) => !has.has(name);
}

/** A donor track replayed over a different duration. Never mutates the shared original. */
function timeScale(track, k) {
  if (k === 1) return track;
  const times = Float32Array.from(track.times, (t) => t * k);
  return { ...track, times };
}

/**
 * Mixamo tracks + the procedural counterpart's tracks for everything Mixamo lacks.
 * `fill = false` gives the pure arm.
 */
function spliceClip(name, mixRaw, donor, fill) {
  const m = compile(name, mixRaw);
  if (!fill || !donor) return m;
  const k = donor.dur > 0 ? m.dur / donor.dur : 1;
  const wants = donorBones(m);
  const bones = m.bones.slice();
  for (const tr of donor.bones) if (wants(tr.name)) bones.push(timeScale(tr, k));
  const scales = m.scales.slice();
  for (const tr of donor.scales) if (wants(tr.name)) scales.push(timeScale(tr, k));
  return {
    ...m,
    bones,
    scales,
    cane: donor.cane ? timeScale(donor.cane, k) : null,
    hold: Math.min(m.dur, donor.hold * k),
    mask: donor.mask || null,
    /* Events are filled by the same rule as bones: the source's own when it has any (the
       emitters derive footsteps for real gaits), else the donor's — time-scaled — so a swap
       cannot silently mute a landing thud or a climb's hand-beat. Donor events live in
       [0, donor.dur], so scaled they live in [0, m.dur] by construction. */
    events: m.events.length ? m.events : donor.events.map((e) => ({ ...e, t: e.t * k })),
  };
}

/**
 * `?anim=` is read at module-load time, the same seam and the same fall-through as `?char=` in
 * `main.js`: a URL param is the only thing reliably set before this module evaluates, with
 * `globalThis.__ANIM_AB` for a runner that boots the page itself. An unknown, misspelled or
 * absent token resolves to `godot` — **the repo's audited movement clips are the shipped
 * default, by the user's instruction; the all-procedural set is one token away (`?anim=proc`),
 * an A/B choice with no `src/` edit and no arm to install.** (Until the FrontFlip commit the
 * default was `proc` and this comment said restoring it was the absence of a token; that claim
 * is deliberately inverted now, and the regime tests were re-derived from the new claim rather
 * than patched around it.)
 */
/**
 * The fall-through, in ONE place. It has to be here rather than at the URL read, because every
 * caller has to get the same answer: a test, a capture runner and the browser must not disagree
 * about what `'mixmao'` means. Returning the raw token to one caller and the resolved one to
 * another is how an arm gets mislabelled while behaving correctly, which is the worst combination.
 */
const REGIMES = ['proc', 'mixamo', 'mixamo-pure', 'godot', 'godot-pure'];
function normaliseRegime(raw) {
  const t = String(raw ?? '').trim().toLowerCase();
  return REGIMES.includes(t) ? t : 'godot';
}

function animRegime() {
  let raw = '';
  try {
    if (typeof location !== 'undefined' && location.search) raw = new URLSearchParams(location.search).get('anim') || '';
    if (!raw && typeof globalThis !== 'undefined' && globalThis.__ANIM_AB != null) raw = String(globalThis.__ANIM_AB);
  } catch { /* plain-module hosts have no location; that is the test path */ }
  return normaliseRegime(raw);
}

/** Build the table this module samples. Exported so tests can build any regime without a URL. */
export function buildClipSet(raw, opts = {}) {
  const regime = normaliseRegime(raw);
  /* §715 — which pair fills the two standing slots. 'repo' (the default): the recovered
     `Idle Anim 1` / `Idle Look`, per the owner's conditional ruling now that the libraries are
     open. 'pose': §479.20's raw `Standupright` in both, bit-exact — the endorsed static. The
     module-load token (`?idle=` / `__IDLE_AB`) decides for ACTIVE; `opts.idle` lets a test
     hold both arms in one process. */
  const idleMode = opts.idle === 'pose' || opts.idle === 'repo' ? opts.idle : (IDLE_REPO ? 'repo' : 'pose');
  /* §716 — which body fills the third combo slot. 'duo' (the default): the library's
     `Cane Hit 2`. 'mono': §479.8's all-`Canehit` chain, verbatim — the revert arm. Same seam
     shape as `idle`: the module-load token decides for ACTIVE; `opts.combo` lets a test hold
     both arms in one process. */
  const comboMode = opts.combo === 'mono' || opts.combo === 'duo' ? opts.combo : (COMBO_DUO ? 'duo' : 'mono');
  const table = Object.create(null);
  const origin = Object.create(null);
  for (const n in CLIPS) { table[n] = CLIPS[n]; origin[n] = 'proc'; }
  if (regime === 'proc') return { table, origin, regime, unused: [] };
  /* §531 — the ruling is about the SHIPPED look, and half of what the player stands still and
     looks at is a procedural pose the swap never reached: the idle carries the most folded
     elbow in the whole set (104°) and the tightest lateral carry (0.51). So the lever's scope
     is the godot REGIME, not just the swapped rows. `proc` returned above untouched, so
     `?anim=proc` stays bit-exact whatever the lever does. Safe against §470 by construction,
     not by luck: that repair moved upperArm phase and head pitch, and this lever only ever
     writes lowerArm/lowerLeg — the sneak gait's own channels are asserted untouched in
     anim.test. */
  const fill = !regime.endsWith('-pure');
  const godot = regime.startsWith('godot');
  /* §715: the godot source table is the gltf bake PLUS the clips recovered from the repo's
     sealed .res libraries (GodotLibClips.js — a separate generated module, so GodotClips.js
     stays byte-identical and §479.20's bit-exactness check keeps meaning). Names cannot
     collide: the lib set's five names exist in no gltf. */
  const SRC = godot ? { ...GODOT_CLIPS, ...GODOT_LIB_CLIPS } : MIXAMO_CLIPS;
  let ALIAS = godot ? GODOT_ALIAS : MIXAMO_ALIAS;
  /* §479.20's endorsed static — and, since §717, the escape hatch for the WHOLE idle family.
     §715's token restored `Standupright` in the two standing slots because those were the only
     slots it had moved. §717 moves two more (`idle_bored`, `balance_idle`), so the token has to
     restore those as well or it stops being a revert and becomes a partial one: the state it
     reproduces is the idle family exactly as §479.20 shipped it — the static in both standing
     slots, and the PROCEDURAL clip in the other two, which is what those verbs held then.
     Dropping the alias rows is how a verb goes back to procedural: the table was seeded from
     CLIPS above and only an ALIAS row overwrites it. */
  if (godot && idleMode === 'pose') {
    ALIAS = { ...ALIAS, idle_confident: 'Standupright', idle_look: 'Standupright' };
    delete ALIAS.idle_bored;
    delete ALIAS.balance_idle;
  }
  if (godot && comboMode === 'mono') ALIAS = { ...ALIAS, cane_combo_3: COMBO_MONO_ROW };  // §716's revert arm

  const tag = godot ? 'godot' : 'mixamo';
  const used = new Set();
  for (const [game, spec] of Object.entries(ALIAS)) {
    const src = typeof spec === 'string' ? spec : spec.src;
    const srcRaw = SRC[src];
    if (!srcRaw || !CLIPS[game]) continue;        // a regenerated module that dropped a clip degrades
    /* `trim`/`until` cut the source to the window that carries the read (§479.8); `dur` pins a
       delivered duration (the flip's window); `rate` pins a delivered PLAYBACK RATE (the
       launch's pace) — dur = authored / rate, so the constant in the table is the measured
       number itself, not its reciprocal baked by hand. `events` hand-carries event times the
       donor-inherit rule would mis-scale (a trimmed strike is not a scaled donor thud). */
    const o = typeof spec === 'object' ? spec : null;
    let timed = o && (o.trim || o.until) ? trimRaw(srcRaw, o.trim || 0, o.until ?? srcRaw.dur) : srcRaw;
    if (o && o.reverse) timed = reverseRaw(timed);            // §479.18 — their play_mode = 1
    if (o && o.dur) timed = retimeRaw(timed, o.dur);
    else if (o && o.rate) timed = retimeRaw(timed, +(timed.dur / o.rate).toFixed(4));
    if (o && o.events) timed = { ...timed, events: o.events };
    let built = spliceClip(game, timed, CLIPS[game], fill);
    if (godot) built = openLimbs(built, limbOpenFor(game));     // §531 — the spread ruling
    /* SOURCE IDENTITY, carried on the clip itself rather than looked up in a side table (§525).
       Two game clips with the same `source` are the SAME authored motion under two names — which
       is the normal case for an imported set with fewer clips than we have verbs (their tree has
       ONE ground attack, so all three combo slots are `godot:Canehit`). `play()` uses this to
       refuse to layer a motion on top of itself; see the one-shot coalesce there for why an
       average of one arc with itself is not a pose the animator ever drew. Procedural clips
       carry NO source — each is its own motion — so the rule cannot reach them. */
    built = { ...built, source: `${tag}:${src}` };
    /* EXCLUSION GROUP travels with the game NAME, not with the data (§526). `spliceClip` returns
       an explicit field list built from the imported clip, so `excl` would otherwise be dropped
       here and silently again in the `-pure` arms — leaving the imported regimes layerable where
       the procedural one is not. Whether two clips may be live together is a statement about the
       action slot, so it is re-applied from the procedural def for every regime. */
    if (CLIPS[game].excl) built.excl = CLIPS[game].excl;
    /* POSTURE travels with the game NAME too, and for the same reason (§529): whether a clip is
       the body's whole pose is a fact about the VERB — a landing absorbs, whatever data draws
       it — so an imported `land_soft` must retire the same tracks the procedural one does. This
       is the third predicate `play()` reads; `--nofix`-style controls and the test arm that
       reconstruct the pre-fix mixer must strip all three, or they silently stop being controls
       (that is precisely how the §525 control broke when §526 added the second one). */
    if (CLIPS[game].posture) built.posture = true;
    table[game] = built;
    origin[game] = `${tag}:${src}`;
    used.add(src);
  }
  /* §531: every clip the godot regime shows, including the ones no alias row swapped */
  if (godot) {
    for (const n in table) {
      if (origin[n] !== 'proc') continue;                      // swapped rows already opened
      /* `origin` names PROVENANCE — which source the motion came from — and the lever is a
         transform, not a source, so it deliberately does not retag. The arms that derive the
         swapped set from CLIP_ORIGIN stay correct. */
      table[n] = openLimbs(table[n], limbOpenFor(n));
    }
  }
  return { table, origin, regime, unused: Object.keys(SRC).filter((n) => !used.has(n)) };
}

